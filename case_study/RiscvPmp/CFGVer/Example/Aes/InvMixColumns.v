  ; Base.MUL A4 A2 A2 false true true   (* mul	A2, A2, A4 *)
  ; RTYPE A1 A2 A1 RISCV_XOR   (* xor	A1, A2, A1 *)
  ; SHIFTIOP (bv.of_Z 6) A0 A2 RISCV_SRLI   (* srli	A2, A0, 6 *)
  ; RTYPE A3 A2 A2 RISCV_AND   (* and	A2, A2, A3 *)
  ; ITYPE (bv.of_Z 27) X0 A4 RISCV_ADDI   (* li	A4, 27 *)
  ; Base.MUL A4 A2 A2 false true true   (* mul	A2, A2, A4 *)
  ; RTYPE A2 A1 A1 RISCV_XOR   (* xor	A1, A1, A2 *)
  ; SHIFTIOP (bv.of_Z 16) A1 A2 RISCV_SRLI   (* srli	A2, A1, 16 *)
  ; SHIFTIOP (bv.of_Z 16) A1 A5 RISCV_SLLI   (* slli	A5, A1, 16 *)
  ; RTYPE A2 A5 A2 RISCV_OR   (* or	A2, A5, A2 *)
  ; RTYPE A1 A0 A0 RISCV_XOR   (* xor	A0, A0, A1 *)
  ; RTYPE A0 A2 A0 RISCV_XOR   (* xor	A0, A2, A0 *)
  ; SHIFTIOP (bv.of_Z 1) A0 A1 RISCV_SLLI   (* slli	A1, A0, 1 *)
  ; UTYPE (bv.of_Z 1044464) A2 RISCV_LUI   (* lui	A2, 1044464 *)
  ; ITYPE (bv.of_Z (-258)) A2 A2 RISCV_ADDI   (* addi	A2, A2, -258 *)
  ; RTYPE A2 A1 A1 RISCV_AND   (* and	A1, A1, A2 *)
  ; SHIFTIOP (bv.of_Z 7) A0 A2 RISCV_SRLI   (* srli	A2, A0, 7 *)
  ; RTYPE A3 A2 A2 RISCV_AND   (* and	A2, A2, A3 *)
  ; Base.MUL A4 A2 A2 false true true   (* mul	A2, A2, A4 *)
  ; SHIFTIOP (bv.of_Z 16) A0 A3 RISCV_SRLI   (* srli	A3, A0, 16 *)
  ; SHIFTIOP (bv.of_Z 16) A0 A4 RISCV_SLLI   (* slli	A4, A0, 16 *)
  ; RTYPE A3 A4 A3 RISCV_OR   (* or	A3, A4, A3 *)
  ; RTYPE A3 A1 A1 RISCV_XOR   (* xor	A1, A1, A3 *)
  ; RTYPE A2 A1 A1 RISCV_XOR   (* xor	A1, A1, A2 *)
