(* Example/Aes/InvMixColumns.v — AES InvMixColumns on one 32-bit column, in  *)
(* two versions, as the case study for the early-terminating-multiplier      *)
(* attack of Grossschaedl, Oswald, Page and Tunstall (ICISC 2009, LNCS 5984, *)
(* pp. 176-192, Sect. 3.1 and Algorithm 7).                                  *)
(*                                                                           *)
(*   imc_linux  Linux lib/crypto/aes.c `inv_mix_columns` (master; used by    *)
(*              aes_expandkey_generic on round keys), whose mul_by_x /       *)
(*              mul_by_x2 reduce with a multiply by 0x1b / 0x36 of a value   *)
(*              built from the top bits of each SECRET byte.  The paper's    *)
(*              vulnerable pattern (its Algorithm 4).                        *)
(*   imc_alg7   the same function with every such multiply replaced by the   *)
(*              paper's constant-time Algorithm 7 (low 32 bits only: the     *)
(*              products fit in 32 bits).                                    *)
(*                                                                           *)
(* Sources and listings: inv_mix_columns_{linux,alg7}.{c,s} next to this     *)
(* file, compiled with `clang --target=riscv32 -march=rv32im -mabi=ilp32     *)
(* -O2 -S`, translated by tools/asm_to_ast.py --drop-ret, then mechanically  *)
(* renamed (a0..a7 -> A0..A7, zero -> X0, the script's six-argument `MUL` -> *)
(* `Base.MUL`, the constructor it denotes).  The two C versions agree on     *)
(* every input tested (C-level check, not a proof).                          *)
(*                                                                           *)
(* NOTE on imc_alg7's C source: without the empty-asm value barriers         *)
(* (OPAQUE) clang -O2 folds Algorithm 7 straight back into `x * y` -- the    *)
(* compiled code is then byte-for-byte the vulnerable imc_linux.  With them, *)
(* every multiply is either  mul gamma, c  with gamma's top byte = 0x01, or  *)
(* mul tau, c  with tau a single bit, which is what Algorithm 7 intends.     *)
(*                                                                           *)
(* In THIS leakage model (no event for MUL) both are straight-line ALU code  *)
(* and are expected to verify; the point of the pair is the multiplier-      *)
(* latency model, under which only imc_alg7 should.                          *)
(*                                                                           *)
(* The instruction lists and reg specs are STATEMENT-RELEVANT: the theorems  *)
(* in InvMixColumnsResult.v reference them by name.                          *)
(* ========================================================================= *)

From Katamaran Require Import RiscvPmp.CFGVer.Example.Prelude.

