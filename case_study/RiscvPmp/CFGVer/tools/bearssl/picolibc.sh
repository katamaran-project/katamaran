#!/usr/bin/env bash
# Assemble picolibc's SIZE-OPTIMISED RISC-V memset/memcpy/memmove for RV32IM
# (PLAN-rsa.md §3 O1). BearSSL leaves these to the platform libc; under -Os
# (__OPTIMIZE_SIZE__) picolibc's libc/machine/riscv/rv_string.h selects the
# hand-written byte-loop assembly: memset 5, memcpy 7, memmove 13 instrs, one
# loop each. LPAD (asm.h) is empty without the Zicfilp extension.
#
# Usage: picolibc.sh <picolibc checkout> <out dir>
#   git clone --depth 1 --branch 1.8.12 https://github.com/picolibc/picolibc.git
# Writes <out>/{memset,memcpy-asm,memmove}.o; link them like the BearSSL .o's.
set -euo pipefail

PICO=$(cd "$1" && pwd)
OUT=$(mkdir -p "$2" && cd "$2" && pwd)
PIN=1.8.12

tag=$(git -C "$PICO" describe --tags --exact-match 2>/dev/null || echo none)
[ "$tag" = "$PIN" ] || echo "warning: picolibc is at $tag, PLAN-rsa.md pins $PIN" >&2

# picolibc.h is generated by picolibc's meson build; rv_string.h only needs it to exist
mkdir -p "$OUT/inc"
: > "$OUT/inc/picolibc.h"

SRC="$PICO/libc/machine/riscv"
for f in memset memcpy-asm memmove; do
  clang --target=riscv32 -march=rv32im -mabi=ilp32 -Os -I"$OUT/inc" -I"$SRC" \
    -c "$SRC/$f.S" -o "$OUT/$f.o"
done
echo "assembled 3 objects in $OUT"
